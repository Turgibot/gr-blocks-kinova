"""Generate worlds/blocks_world.sdf and worlds/textures/<LETTER>.png from data/blockworld.json.

    python3 -m gr_blocks_ros.make_world [--blockworld PATH] [--out DIR]

Layout (robot base is spawned at z = TABLE_Z, x = y = 0, facing +x): three tower slots in front of the arm,
tower 1 of blockworld.json on the left (+y). Towers are listed top to bottom, so the last letter sits on the table.
"""
import argparse
import json
import math
from pathlib import Path

import matplotlib
from PIL import Image, ImageDraw, ImageFont

CUBE = 0.045          # m
SLOT_X = 0.45         # m, distance of the towers from the robot base
SLOT_DY = 0.12        # m, spacing between towers
TABLE_Z = 0.30        # m, table top (robot base height set by the sim launch)
TABLE_X0, TABLE_X1 = -0.25, 0.85   # m, table extent along x: the robot base (x=0) stands on it
TABLE_Y = 1.00        # m, table width
GAP = 0.0005          # m, initial clearance between stacked cubes
MASS = 0.1            # kg
MU = 1.0

FONT = Path(matplotlib.__file__).parent / "mpl-data/fonts/ttf/DejaVuSans-Bold.ttf"


def letter_png(letter: str, path: Path, size=256, border=14):
    im = Image.new("RGB", (size, size), (214, 170, 110))
    d = ImageDraw.Draw(im)
    d.rectangle([border, border, size - border, size - border], fill=(240, 222, 186), outline=(150, 100, 50), width=6)
    font = ImageFont.truetype(str(FONT), 170)
    b = d.textbbox((0, 0), letter, font=font)
    d.text(((size - (b[2] - b[0])) / 2 - b[0], (size - (b[3] - b[1])) / 2 - b[1]), letter, font=font, fill=(40, 70, 150))
    im.save(path)


def block_sdf(letter, x, y, z):
    i = MASS * CUBE**2 / 6
    return f"""
    <model name="block_{letter}">
      <pose>{x:.4f} {y:.4f} {z:.4f} 0 0 0</pose>
      <link name="link">
        <inertial><mass>{MASS}</mass><inertia><ixx>{i:.3e}</ixx><iyy>{i:.3e}</iyy><izz>{i:.3e}</izz><ixy>0</ixy><ixz>0</ixz><iyz>0</iyz></inertia></inertial>
        <collision name="c"><geometry><box><size>{CUBE} {CUBE} {CUBE}</size></box></geometry>
          <surface><friction><ode><mu>{MU}</mu><mu2>{MU}</mu2></ode></friction></surface></collision>
        <visual name="v"><geometry><box><size>{CUBE} {CUBE} {CUBE}</size></box></geometry>
          <material><diffuse>1 1 1 1</diffuse><pbr><metal><albedo_map>textures/{letter}.png</albedo_map><metalness>0</metalness><roughness>0.9</roughness></metal></pbr></material></visual>
      </link>
    </model>"""


def camera_sdf(name, pos, target, w=1280, h=720, hfov=1.1):
    dx, dy, dz = (target[i] - pos[i] for i in range(3))
    yaw = math.atan2(dy, dx)
    pitch = math.atan2(-dz, math.hypot(dx, dy))
    return f"""
    <model name="{name}">
      <static>true</static>
      <pose>{pos[0]} {pos[1]} {pos[2]} 0 {pitch:.4f} {yaw:.4f}</pose>
      <link name="link"><sensor name="cam" type="camera">
        <camera><horizontal_fov>{hfov}</horizontal_fov><image><width>{w}</width><height>{h}</height></image>
          <clip><near>0.05</near><far>10</far></clip></camera>
        <always_on>1</always_on><update_rate>5</update_rate><visualize>false</visualize><topic>{name}/image</topic>
      </sensor></link>
    </model>"""


def build(blockworld: Path, out: Path):
    towers = json.loads(blockworld.read_text())["towers"]
    (out / "textures").mkdir(parents=True, exist_ok=True)
    blocks = []
    n = len(towers)
    for t, tower in enumerate(towers):
        y = (n - 1) / 2 * SLOT_DY - t * SLOT_DY           # tower 1 on the left (+y)
        for k, letter in enumerate(reversed(tower)):      # bottom first
            z = TABLE_Z + CUBE / 2 + GAP + k * (CUBE + GAP)
            blocks.append(block_sdf(letter, SLOT_X, y, z))
            letter_png(letter, out / "textures" / f"{letter}.png")
    table_h = TABLE_Z
    sdf = f"""<?xml version="1.0"?>
<!-- GENERATED by gr_blocks_ros.make_world from data/blockworld.json. Do not edit by hand. -->
<sdf version="1.9">
  <world name="blocks_world">
    <physics name="1ms" type="ignored"><max_step_size>0.001</max_step_size><real_time_factor>1.0</real_time_factor></physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <!-- No Sensors system here: the robot description (kinova.urdf.xacro) already loads one, and two of them
         crash the server (duplicate Ogre2 materials). The view cameras therefore render once the robot is spawned. -->
    <plugin filename="gz-sim-contact-system" name="gz::sim::systems::Contact"/>
    <gravity>0 0 -9.81</gravity>
    <scene><ambient>0.5 0.5 0.5 1</ambient><background>0.8 0.85 0.9 1</background></scene>
    <light type="directional" name="sun"><cast_shadows>true</cast_shadows><pose>0 0 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse><specular>0.2 0.2 0.2 1</specular><direction>-0.4 0.3 -1</direction></light>
    <model name="ground"><static>true</static><link name="link">
      <collision name="c"><geometry><plane><normal>0 0 1</normal><size>20 20</size></plane></geometry></collision>
      <visual name="v"><geometry><plane><normal>0 0 1</normal><size>20 20</size></plane></geometry>
        <material><diffuse>0.55 0.55 0.55 1</diffuse></material></visual></link></model>
    <model name="table"><static>true</static><pose>{(TABLE_X0 + TABLE_X1) / 2:.3f} 0 {table_h / 2:.3f} 0 0 0</pose><link name="link">
      <collision name="c"><geometry><box><size>{TABLE_X1 - TABLE_X0:.3f} {TABLE_Y:.3f} {table_h}</size></box></geometry>
        <surface><friction><ode><mu>{MU}</mu><mu2>{MU}</mu2></ode></friction></surface></collision>
      <visual name="v"><geometry><box><size>{TABLE_X1 - TABLE_X0:.3f} {TABLE_Y:.3f} {table_h}</size></box></geometry>
        <material><diffuse>0.45 0.32 0.2 1</diffuse></material></visual></link></model>
{''.join(blocks)}
{camera_sdf("view_cam", (1.25, -0.85, 0.95), (SLOT_X, 0.0, TABLE_Z + 0.1))}
{camera_sdf("top_cam", (SLOT_X, 0.0, 1.35), (SLOT_X, 0.0, TABLE_Z), hfov=0.9)}
  </world>
</sdf>
"""
    (out / "blocks_world.sdf").write_text(sdf)
    return len(blocks)


def main():
    here = Path(__file__).resolve()
    repo = here.parents[2]
    ap = argparse.ArgumentParser()
    ap.add_argument("--blockworld", type=Path, default=repo / "data" / "blockworld.json")
    ap.add_argument("--out", type=Path, default=repo / "gr_blocks_ros" / "worlds")
    a = ap.parse_args()
    print("wrote", build(a.blockworld, a.out), "blocks to", a.out)


if __name__ == "__main__":
    main()
